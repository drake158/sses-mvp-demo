import type { ConstanciaReporte, SsesState } from '../types/sses';
import { enmascararDocumentoLey1581 } from './businessRules';
import { computeSha256Hex } from './crypto';

const CSV_HEADERS = [
  'estrategia_id',
  'estrategia_nombre',
  'entidad_codigo_dane',
  'entidad_nombre',
  'estado_estrategia',
  'fecha_inicio',
  'fecha_fin',
  'estudiante_documento',
  'estudiante_nombre',
  'semanas_realizadas',
  'semanas_no_realizadas',
  'semanas_pendientes',
  'porcentaje_cumplimiento',
] as const;

function escapeCsvCell(value: string | number): string {
  const str = String(value);
  if (/[",\r\n]/.test(str)) {
    return `"${str.replace(/"/g, '""')}"`;
  }
  return str;
}

export interface GeneratedCsvReport {
  csvContent: string;
  constancia: ConstanciaReporte;
}

/**
 * Builds an RFC-4180 CSV with UTF-8 BOM, applies Ley 1581 masking automatically
 * when generated by ENTE_CONTROL, and computes a real SHA-256 receipt over the
 * exact exported content.
 */
export async function buildComplianceCsvReport(
  state: SsesState,
  rolGenerador: 'FUNCIONARIO_MEN' | 'ENTE_CONTROL'
): Promise<GeneratedCsvReport> {
  const enmascaradoLey1581 = rolGenerador === 'ENTE_CONTROL';
  const entidadById = new Map(state.entidades.map((e) => [e.id, e]));
  const estudianteById = new Map(state.estudiantes.map((s) => [s.id, s]));

  const rows: string[][] = [];

  for (const estrategia of state.estrategias) {
    const entidad = entidadById.get(estrategia.entidadId);
    const acomps = state.acompanamientos.filter(
      (a) => a.estrategiaId === estrategia.id
    );

    let realizadas = 0;
    let noRealizadas = 0;
    let pendientes = 0;

    for (const acomp of acomps) {
      for (const sem of acomp.semanas) {
        if (sem.estado === 'REALIZADO') realizadas += 1;
        else if (sem.estado === 'NO_REALIZADO') noRealizadas += 1;
        else pendientes += 1;
      }
    }

    const totalSemanas = realizadas + noRealizadas + pendientes;
    const pctCumplimiento =
      totalSemanas === 0 ? 0 : Math.round((realizadas / totalSemanas) * 100);

    if (estrategia.estudianteIds.length === 0) {
      rows.push([
        estrategia.id,
        estrategia.nombre,
        entidad?.codigoDane ?? '',
        entidad?.nombre ?? estrategia.entidadId,
        estrategia.estado,
        estrategia.fechaInicio,
        estrategia.fechaFin,
        '',
        'Sin estudiantes vinculados',
        String(realizadas),
        String(noRealizadas),
        String(pendientes),
        `${pctCumplimiento}%`,
      ]);
      continue;
    }

    for (const estId of estrategia.estudianteIds) {
      const est = estudianteById.get(estId);
      const docDisplay = est
        ? enmascaradoLey1581
          ? enmascararDocumentoLey1581(est.tipoDocumento, est.numeroDocumento)
          : `${est.tipoDocumento} ${est.numeroDocumento}`
        : '';

      rows.push([
        estrategia.id,
        estrategia.nombre,
        entidad?.codigoDane ?? '',
        entidad?.nombre ?? estrategia.entidadId,
        estrategia.estado,
        estrategia.fechaInicio,
        estrategia.fechaFin,
        docDisplay,
        est?.nombreCompleto ?? estId,
        String(realizadas),
        String(noRealizadas),
        String(pendientes),
        `${pctCumplimiento}%`,
      ]);
    }
  }

  const headerLine = CSV_HEADERS.map(escapeCsvCell).join(',');
  const dataLines = rows.map((row) => row.map(escapeCsvCell).join(','));
  const csvContent = `\uFEFF${[headerLine, ...dataLines].join('\r\n')}\r\n`;

  const sha256 = await computeSha256Hex(csvContent);
  const now = new Date();
  const dateStamp = now.toISOString().slice(0, 10);
  const prefix = enmascaradoLey1581
    ? 'sses-reporte-ley-1581'
    : 'sses-reporte-cumplimiento-men';
  const nextIndex = state.constanciasReportes.length + 1;
  const constancia: ConstanciaReporte = {
    id: `REP-${String(nextIndex).padStart(3, '0')}`,
    nombreArchivo: `${prefix}-${dateStamp}-${String(nextIndex).padStart(3, '0')}.csv`,
    generadoEn: now.toISOString(),
    rolGenerador,
    enmascaradoLey1581,
    totalRegistros: rows.length,
    sha256,
  };

  return { csvContent, constancia };
}

/**
 * Triggers a client-side CSV download in browser contexts.
 */
export function triggerCsvDownload(
  nombreArchivo: string,
  csvContent: string
): void {
  if (typeof document === 'undefined' || typeof URL === 'undefined') {
    return;
  }

  const blob = new Blob([csvContent], { type: 'text/csv;charset=utf-8;' });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.setAttribute('download', nombreArchivo);
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}
